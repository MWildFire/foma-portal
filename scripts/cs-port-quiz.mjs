// Converts the FomaCS quiz (js/data.js, window.QUIZ_DATA) into content/cs/theme-a/questions/ported.ts.
// Usage: node scripts/cs-port-quiz.mjs [path/to/FomaCS/js/data.js]
// The output is generated: change this script and rerun it instead of editing ported.ts by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2] || path.join(homedir(), 'Projects', 'FomaCS', 'js', 'data.js');
const output = path.join(root, 'content', 'cs', 'theme-a', 'questions', 'ported.ts');

// FomaCS topic code -> portal topic id. Sub-topics (A2.1.4, A2.1.5) belong to their unit (A2.1).
// Theme A1 has no quiz items in FomaCS, so it is not listed here.
const TOPIC_BY_CODE = {
  'A2.1': 'a2-1-fundamentals',
  'A2.2': 'a2-2-architecture',
  'A2.3': 'a2-3-transmissions',
  'A3.1': 'a3-1-fundamentals',
  'A3.2': 'a3-2-design',
  'A3.3': 'a3-3-sql',
  'A3.4': 'a3-4-alternative-databases',
  'A4.1': 'a4-1-ml-fundamentals',
  'A4.2': 'a4-2-preprocessing',
  'A4.3': 'a4-3-approaches',
  'A4.4': 'a4-4-ethics',
};

// Command labels from FomaCS that are not in the IB command-term table (Oxford 2025, pp. 602-603) map to the closest term.
const COMMAND_MAP = { 'Compare and contrast': 'Compare', Contrast: 'Distinguish', 'Identify + describe': 'Identify' };

const sandbox = { window: {} };
vm.runInNewContext(readFileSync(source, 'utf8'), sandbox, { filename: source });
const items = sandbox.window.QUIZ_DATA;
if (!Array.isArray(items)) throw new Error(`QUIZ_DATA not found in ${source}`);

// The FomaCS text uses <b> for emphasis; the portal L texts use inline Markdown.
const toMarkdown = (text) => String(text)
  .replace(/<b>([\s\S]*?)<\/b>/g, '**$1**')
  .replace(/<[^>]+>/g, '')
  .replace(/\s+/g, ' ')
  .trim();

const joinBullets = (lines) => lines.map(toMarkdown).filter(Boolean).join(' ');

const seen = new Set();
const problems = [];
const perTopic = new Map();
const commands = new Map();
const rows = [];

for (const item of items) {
  const code = String(item.topic).split('.').slice(0, 2).join('.');
  const topicId = TOPIC_BY_CODE[code];
  if (!topicId) {
    problems.push(`${item.id}: no portal topic for FomaCS topic "${item.topic}"`);
    continue;
  }
  const id = `port-${String(item.id).toLowerCase().replace(/\./g, '-')}`;
  if (seen.has(id)) problems.push(`${id}: duplicate id`);
  seen.add(id);
  const command = COMMAND_MAP[item.command] || item.command;
  commands.set(command, (commands.get(command) || 0) + 1);
  const prompt = { en: toMarkdown(item.q.en), ru: toMarkdown(item.q.ru) };
  const markscheme = { en: joinBullets(item.model.en), ru: joinBullets(item.model.ru) };
  if (!markscheme.en || !markscheme.ru) problems.push(`${id}: empty model answer`);
  perTopic.set(topicId, (perTopic.get(topicId) || 0) + 1);
  rows.push({ id, topicId, marks: item.marks, command, prompt, markscheme });
}

const q = (value) => JSON.stringify(value);
const body = rows.map((row) => `  {
    id: ${q(row.id)},
    subject: 'cs',
    topicIds: [${q(row.topicId)}],
    paper: 'P1',
    section: 'A',
    marks: ${row.marks},
    command: ${q(row.command)},
    prompt: { en: ${q(row.prompt.en)}, ru: ${q(row.prompt.ru)} },
    markscheme: { en: ${q(row.markscheme.en)}, ru: ${q(row.markscheme.ru)} },
    origin: 'original',
  },`).join('\n');

const file = `import type { Question } from '../../../../src/contract/types';

// Generated by scripts/cs-port-quiz.mjs from the FomaCS quiz (js/data.js, ${items.length} items). Edit the script, not this file.
// The items were written for the FomaCS project itself, so they are original. Topic HL status lives in each topic's meta.
export const questions: Question[] = [
${body}
];
`;

writeFileSync(output, file, 'utf8');
console.log(`wrote ${rows.length} questions to ${path.relative(root, output)}`);
console.log('per topic:', Object.fromEntries([...perTopic.entries()].sort()));
console.log('command terms:', Object.fromEntries([...commands.entries()].sort()));
if (problems.length > 0) {
  console.log(`skipped or flagged (${problems.length}):`);
  problems.forEach((line) => console.log(`  ${line}`));
  process.exitCode = 1;
}
